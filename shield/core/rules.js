export const CATEGORY_CAPS = Object.freeze({ link: 45, sender: 35, header: 10, attachment: 40, language: 40, combination: 25 });

/** Build a finding. Every finding must carry concrete evidence and a source location.
 *  Stable ids are assigned by the analyzer after all findings are collected (no module-level state). */
export function makeFinding(ruleId, { evidence, source, excerpt = null, domain = null, url = null, details = null, priority = null, points = null, context_flags = [] }) {
  const r = RULES[ruleId];
  if (!r) throw new Error("Unknown rule " + ruleId);
  if (!evidence || !source) throw new Error("Finding " + ruleId + " requires evidence and a source");
  return {
    id: null,
    rule: ruleId,
    category: r.category,
    basis: r.basis,
    title: r.title,
    evidence: String(evidence),
    source: String(source),
    excerpt,
    domain,
    url,
    details,
    priority: priority ?? r.priority,
    points: points ?? r.points,
    why: r.why,
    false_positive_notes: r.fp,
    next_action: r.action,
    context_flags
  };
}
